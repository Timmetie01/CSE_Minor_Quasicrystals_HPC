def multiplication_by_int(a, b=10):
    '''
    This is a function purely made to test docstrings. hover over the function name to see the docstring in action.

    This function multiplies a by b, and returns the result. It raises a TypeError if b is not an integer.
    
    :param a: this is an argument. It should be a np array, float or int.
    :param b: this is a keyword-argument. It should be an integer, and defaults to 10 if not called
    :returns: this is what the function returns, it is of the type of arg a
    :raises TypeError: this can be generated by the function if a certain thing goes wrong (in this case the user didnt RTFM and did not enter b as the correct type)
    '''
    if type(b) is not int:
        raise TypeError("Variable b should be an integer.")
    return a*b



#Below is an extremely basic object-oriënted programming example. 

#Classes use PascalCase by convention
class TrainClass:
    '''
    This Class functions as an example and represents a train. Pay attention to the fact that class names use PascalCase :)
    '''

    #The underscores mean it is a standard function for the classes. "init" means that is what runs when creating it
                #self should always be passed to any function defined in a class.
    def __init__(self, wagon_count, power):
        '''
        The ExampleClass is initiated by assigning it a wagon_count

        :param wagon_count: The amount of train cars this class has
        :param power: The amount of power (kW) the motors of the train deliver
        '''
        self.wagon_count = wagon_count 
        self.power = power


    #This will be called when using the "+"-operator on two of these classes
    def __add__(self, other):
        '''
        Adds two instances of the ExampleClass by summing their wagons and power
        '''
        return TrainClass(self.wagon_count + other.wagon_count, self.power + other.power)

    def list_train_stats(self):
        print(f'This train has {self.wagon_count} wagons.')
        print(f'This train has {self.power} kW of power.')


train1 = TrainClass(4, 100)
train2 = TrainClass(6, 200)
#Because we have defined an operation that the class does when adding, the following works. We can couple trains!
train3 = train1 + train2
train3.list_train_stats()
